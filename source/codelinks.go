// codeLinks: Task -> Cost codes (الموجودين في القايمة بس)
func codeLinks(cl *CodeLists) map[string][]string {
	okC := map[string]bool{}
	if cl != nil {
		for _, c := range cl.Cost {
			okC[c.Code] = true
		}
	}
	out := map[string][]string{}
	add := func(t, c string) {
		if t == "" || c == "" || (len(okC) > 0 && !okC[c]) {
			return
		}
		for _, x := range out[t] {
			if x == c {
				return
			}
		}
		out[t] = append(out[t], c)
	}
	for t, cs := range taskCostSeed {
		for _, c := range strings.Fields(cs) {
			add(t, c)
		}
	}
	for _, r := range finSeed { // أزواج معتمدة في Company Books
		add(r.task, r.cost)
	}
	return out
}
